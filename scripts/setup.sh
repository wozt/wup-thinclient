#!/usr/bin/env bash
# WUP ThinClient — toolchain + dependency setup (idempotent).
#
#   scripts/setup.sh
#
# What it does:
#   1. Resolves the libwup SDK: $LIBWUP_DIR if set, else the pinned
#      third_party/wup-homebrew submodule (wupbuild.py must exist).
#   2. Detects an LLVM toolchain (clang, ld.lld, llvm-ar, llvm-nm,
#      llvm-objcopy) and records it in build/env.sh — no manual symlinks.
#   3. Pre-fetches the third-party sources the build needs (littlefs,
#      lwIP, tinf, heatshrink); picolibc/compiler-rt are fetched by the
#      SDK itself on first build.
#
# Environment overrides:
#   LIBWUP_DIR   path to a libwup checkout (dir containing tools/wupbuild.py)
#   LLVM_BIN     path to an LLVM bin dir (skips auto-detection)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

LIBWUP_DIR="${LIBWUP_DIR:-$ROOT/third_party/wup-homebrew/libwup}"
BUILD_DIR="$ROOT/build"
mkdir -p "$BUILD_DIR"

# --- 1. SDK ---------------------------------------------------------------
if [ ! -f "$LIBWUP_DIR/tools/wupbuild.py" ] && [ -f .gitmodules ]; then
    git submodule update --init --recursive third_party/wup-homebrew
fi
if [ ! -f "$LIBWUP_DIR/tools/wupbuild.py" ]; then
    if [ -f "$ROOT/third_party/wup-homebrew/libwup/tools/wupbuild.py" ]; then
        LIBWUP_DIR="$ROOT/third_party/wup-homebrew/libwup"
    else
        echo "setup: SDK not found at $LIBWUP_DIR" >&2
        echo "setup: run 'git submodule update --init --recursive' or set LIBWUP_DIR" >&2
        exit 1
    fi
fi
echo "setup: libwup SDK = $LIBWUP_DIR"

# --- 2. LLVM toolchain -----------------------------------------------------
have_all() { for t in clang ld.lld llvm-ar llvm-nm llvm-objcopy; do [ -x "$1/$t" ] || return 1; done; }

LLVM_BIN="${LLVM_BIN:-}"
if [ -z "$LLVM_BIN" ] || ! have_all "$LLVM_BIN"; then
    LLVM_BIN=""
    for d in /usr/lib/llvm-*/bin /usr/local/llvm-*/bin /opt/llvm-*/bin; do
        [ -d "$d" ] || continue
        have_all "$d" && LLVM_BIN="$d"
    done
    # highest version wins among /usr/lib/llvm-* candidates
    best=""
    for d in /usr/lib/llvm-*/bin; do
        [ -d "$d" ] || continue
        have_all "$d" || continue
        v="${d#/usr/lib/llvm-}"; v="${v%%/*}"
        if [ -z "$best" ] || [ "$v" -gt "${best#/usr/lib/llvm-}" ] 2>/dev/null; then best="$d"; fi
    done
    [ -n "$best" ] && LLVM_BIN="$best"
fi
if [ -z "$LLVM_BIN" ]; then
    # fall back to whatever PATH provides
    ok=1
    for t in clang ld.lld llvm-ar llvm-nm llvm-objcopy; do command -v "$t" >/dev/null 2>&1 || ok=0; done
    [ "$ok" = 1 ] && LLVM_BIN="$(dirname "$(command -v clang)")"
fi
if [ -z "$LLVM_BIN" ] || ! have_all "$LLVM_BIN"; then
    echo "setup: no complete LLVM toolchain found (need clang, ld.lld, llvm-ar, llvm-nm, llvm-objcopy)" >&2
    echo "setup: install LLVM (e.g. 'apt install llvm clang lld') or set LLVM_BIN=/path/to/llvm/bin" >&2
    exit 1
fi

{
    echo "# generated by scripts/setup.sh — do not edit"
    echo "export LIBWUP_DIR='$LIBWUP_DIR'"
    echo "export LLVM_BIN='$LLVM_BIN'"
    echo "export PATH='$LLVM_BIN':\"\$PATH\""
} > "$BUILD_DIR/env.sh"
echo "setup: LLVM_BIN = $LLVM_BIN"

# --- 3. third-party sources -------------------------------------------------
# Fetch only what the app build needs (the SDK fetches picolibc/compiler-rt
# itself on first link). deps.fetch() is idempotent.
( cd "$LIBWUP_DIR" && python3 - <<'PY'
import sys, os
sys.path.insert(0, 'tools')
import deps
deps.fetch('littlefs', 'lwip', 'tinf')
PY
) || { echo "setup: dependency fetch failed" >&2; exit 1; }

echo "setup: OK — run 'make' to build"
